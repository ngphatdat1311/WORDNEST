// Academic/Latinate suffixes indicative of B2-C1 vocabulary when not in explicit frequency sets
const ACADEMIC_SUFFIX_RE =
  /(?:ology|graphy|cracy|phobia|philia|escence|acious|itious|loqu|morph|chron|path|cide|metry|ism|ist|ity|tion|sion|ment|ence|ance|tude|ize|ise|ify|ate)$/i;

export interface CefrClassification {
  cefr: CefrBand;
  level: WordLevel;
}

/**
 * Classifies an English word or phrase into a CEFR band (A1–C2) and WordLevel (easy/medium/hard)
 * using curated frequency lists + lemma normalization + morphological complexity instead of raw length.
 */
export function classifyWordCefr(rawWord: string): CefrClassification {
  const clean = rawWord.trim().toLowerCase().replace(/^[^a-z]+|[^a-z]+$/g, '');
  if (!clean) return { cefr: 'B1', level: 'medium' };

  // Multi-word phrases / phrasal verbs: score based on head content words
  if (clean.includes(' ')) {
    const parts = clean.split(/\s+/).filter((p) => p.length >= 2);
    if (parts.some((p) => C1_C2_WORDS.has(p))) {
      return { cefr: 'C1', level: 'hard' };
    }
    if (parts.every((p) => A1_A2_WORDS.has(p))) {
      return { cefr: 'B1', level: 'medium' }; // Phrasal verbs like "give up" / "figure out" are B1
    }
    return { cefr: 'B2', level: 'medium' };
  }

  const candidates = [clean, ...getLemmaCandidates(clean)];

  for (const w of candidates) {
    if (A1_A2_WORDS.has(w)) {
      return { cefr: w.length <= 5 ? 'A1' : 'A2', level: 'easy' };
    }
  }

  for (const w of candidates) {
    if (C1_C2_WORDS.has(w)) {
      return { cefr: w.length >= 10 ? 'C2' : 'C1', level: 'hard' };
    }
  }

  for (const w of candidates) {
    if (B1_B2_WORDS.has(w)) {
      return { cefr: w.length <= 7 ? 'B1' : 'B2', level: 'medium' };
    }
  }

  // Fallback for unseen words: use morphological & syllable heuristics (never penalizing simple compounds)
  const vowelGroups = (clean.match(/[aeiouy]+/g) || []).length;
  const hasRareLetters = /[qxzj]/.test(clean) || /(?:ph|ps|pt|mn|gn|rh|ae|oe|eu)/.test(clean);
  if (vowelGroups >= 4 || (ACADEMIC_SUFFIX_RE.test(clean) && (clean.length >= 10 || hasRareLetters))) {
    return { cefr: 'C1', level: 'hard' };
  }
  if (vowelGroups >= 3 || ACADEMIC_SUFFIX_RE.test(clean) || clean.length >= 7) {
    return { cefr: 'B2', level: 'medium' };
  }
  return { cefr: 'B1', level: 'medium' };
}
